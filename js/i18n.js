// t('chiave', { n: 3 }) sostituisce {n} nel testo.
export function t(key, params = {}) {
  const text = STRINGS[lang][key] ?? STRINGS.it[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
}

